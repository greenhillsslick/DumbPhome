# dumbOS pixel font (5x7 dot-matrix, Nokia-style)
# Every glyph is 5 columns x 7 rows. Only '#' is ink.
# G = 4x6 small capitals (status bar, titles, keys)

BIG = {}

def g(ch, rows):
    assert len(rows) == 7, (ch, len(rows))
    for r in rows:
        assert len(r) == 5, (ch, r)
    BIG[ch] = rows

