    from PIL import Image, ImageDraw
    PX = 8
    def render(ch, rows, x, y, d, ink, W):
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c == '#':
                    d.rectangle([x + rx*PX, y + ry*PX, x + rx*PX + PX - 1, y + ry*PX + PX - 1], fill=ink)

    big_chars = sorted(BIG.keys())
    small_chars = sorted(SMALL.keys())
    per_row = 16
    cols_w = 6 * PX
    img = Image.new('RGB', (per_row * cols_w + 40, 1600), (10, 20, 8))
    d = ImageDraw.Draw(img)
    y = 10
    for i, ch in enumerate(big_chars + list(SYMBOL_GLYPHS.keys())):
        rows = BIG.get(ch) or SYMBOL_GLYPHS[ch]
        cx = 10 + (i % per_row) * cols_w
        cy = y + (i // per_row) * 8 * PX
        render(ch, rows, cx, cy, d, (196, 255, 176), img.width)
    y += ((len(big_chars) + len(SYMBOL_GLYPHS)) // per_row + 1) * 8 * PX + 20
    per_row_s = 24
    cols_s = 5 * PX
    for i, ch in enumerate(small_chars):
        cx = 10 + (i % per_row_s) * cols_s
        cy = y + (i // per_row_s) * 7 * PX
        render(ch, SMALL[ch], cx, cy, d, (196, 255, 176), img.width)
    img = img.crop((0, 0, img.width, y + 8 * 7 * PX))
    img.save('/tmp/font_specimen.png')
    print('big', len(big_chars), 'small', len(small_chars), 'sym', len(SYMBOL_GLYPHS))
